import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { LEGACY_CONDITION_ICONS } from '@lorkarium/contracts';
import { CONDITION_ICON_SUGGESTIONS } from '../src/lib/condition-icon-suggestions';
import { conditionIconLibraryOf, conditionIconNameOf } from '../src/lib/condition-icon-search';
import { CONDITION_ICONS_VERSION } from '../src/lib/condition-icon-version';
import { conditionIconFileOf } from '../src/lib/condition-icons';

type IconifyIcon = Readonly<{ body: string; width?: number; height?: number }>;
type IconifySet = Readonly<{ width?: number; height?: number; icons: Record<string, IconifyIcon> }>;
export type IconSets = Readonly<
  Record<'game-icons' | 'lucide' | 'tabler' | 'ph' | 'mdi', IconifySet>
>;

const LIBRARIES = ['game-icons', 'lucide', 'tabler', 'ph', 'mdi'] as const;
// The stroke of the 28 Lucide icons of before, on the board and in the lists.
const STROKE_WIDTH = '2.5';
// The texture side the board loads (pixi-texture-cache); the DOM scales the mask anyway.
const SVG_SIDE = 128;
const LEGACY: ReadonlySet<string> = new Set(LEGACY_CONDITION_ICONS);

/** The five `@iconify-json/*` packages the condition icons come from, as installed.
 *
 *  Example: `readIconSets()['game-icons'].icons.manacles.body` */
export function readIconSets(): IconSets {
  const require = createRequire(import.meta.url);
  const read = (library: string): IconifySet =>
    JSON.parse(readFileSync(require.resolve(`@iconify-json/${library}/icons.json`), 'utf8'));
  return Object.fromEntries(LIBRARIES.map((library) => [library, read(library)])) as IconSets;
}

/** The icon of a key in its package, or `undefined` when the package has none by that name.
 *
 *  Example: `sourceOf(sets, 'skull')?.body` */
export function sourceOf(sets: IconSets, key: string): IconifyIcon | undefined {
  return sets[conditionIconLibraryOf(key)].icons[conditionIconNameOf(key)];
}

/** The icon as a white SVG (fill or stroke), so the board tints it and the DOM masks it; strokes
 *  get the 2.5 width of before.
 *
 *  Example: `whiteSvgOf(sets, 'game-icons:manacles') // '<svg … viewBox="0 0 512 512">…'` */
export function whiteSvgOf(sets: IconSets, key: string): string {
  const library = conditionIconLibraryOf(key);
  const icon = sourceOf(sets, key);
  if (!icon)
    throw new Error(
      `Icon ${key} is not in @iconify-json/${library}: expected one of its icon names`,
    );
  const width = icon.width ?? sets[library].width ?? 16;
  const height = icon.height ?? sets[library].height ?? 16;
  const body = icon.body
    .replaceAll('currentColor', '#fff')
    .replaceAll('stroke-width="2"', `stroke-width="${STROKE_WIDTH}"`);
  const side = `width="${SVG_SIDE}" height="${Math.round((SVG_SIDE * height) / width)}"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" ${side} viewBox="0 0 ${width} ${height}">${body}</svg>`;
}

/** A short hash of every served icon: the folder name, which changes whenever one body changes, so
 *  the immutable cache never serves an old drawing.
 *
 *  Example: `iconsVersionOf(sets, CONDITION_ICONS) // '3f2a9c01be'` */
export function iconsVersionOf(sets: IconSets, keys: readonly string[]): string {
  const hash = createHash('sha256');
  for (const key of keys) hash.update(`${key}\n${whiteSvgOf(sets, key)}\n`);
  return hash.digest('hex').slice(0, 10);
}

/** The keys the contract adds to the 28 of before: every Game-icon and the curated icons of the
 *  other libraries, never a prefixed copy of one of the 28.
 *
 *  Example: `contractKeysOf(sets, suggestedKeys)[0] // 'game-icons:aaa'` */
export function contractKeysOf(sets: IconSets, curated: readonly string[]): readonly string[] {
  const gameIcons = Object.keys(sets['game-icons'].icons).map((name) => `game-icons:${name}`);
  const others = curated.filter((key) => {
    const library = conditionIconLibraryOf(key);
    if (library === 'game-icons' || !key.includes(':')) return false;
    return library !== 'lucide' || !LEGACY.has(conditionIconNameOf(key));
  });
  return [...new Set([...gameIcons, ...others.sort()])];
}

function keysModule(keys: readonly string[]): string {
  const lines = keys.map((key) => `  '${key}',`).join('\n');
  return `// Generated by \`pnpm icons:keys\` (client/scripts/generate-condition-icons.ts): do not edit.\n\n/** The condition icons beyond the 28 of before: every Game-icon and the curated others. */\nexport const CONDITION_ICON_KEYS = [\n${lines}\n] as const;\n`;
}

function versionModule(version: string): string {
  return `// Generated by \`pnpm icons:keys\` (client/scripts/generate-condition-icons.ts): do not edit.\n\n/** The folder of the served icon files: changes when one body changes. */\nexport const CONDITION_ICONS_VERSION = '${version}';\n`;
}

const here = path.dirname(fileURLToPath(import.meta.url));
const KEYS_FILE = path.join(here, '../../packages/contracts/src/board/condition-icon-keys.ts');
const VERSION_FILE = path.join(here, '../src/lib/condition-icon-version.ts');
const PUBLIC_DIR = path.join(here, '../public/condition-icons');

async function writeKeys(sets: IconSets): Promise<void> {
  const curated = CONDITION_ICON_SUGGESTIONS.flatMap((suggestion) => suggestion.keys);
  const keys = contractKeysOf(sets, curated);
  await writeFile(KEYS_FILE, keysModule(keys));
  await writeFile(
    VERSION_FILE,
    versionModule(iconsVersionOf(sets, [...LEGACY_CONDITION_ICONS, ...keys])),
  );
  process.stdout.write(`ícones de condição: ${keys.length} chaves novas no contrato\n`);
}

async function writeSvgs(sets: IconSets): Promise<void> {
  const { CONDITION_ICONS } = await import('@lorkarium/contracts');
  const version = iconsVersionOf(sets, CONDITION_ICONS);
  if (version !== CONDITION_ICONS_VERSION) {
    throw new Error(
      `Condition icons changed (${CONDITION_ICONS_VERSION} written, ${version} installed): expected \`pnpm icons:keys\` first`,
    );
  }
  const folder = path.join(PUBLIC_DIR, version);
  await rm(PUBLIC_DIR, { recursive: true, force: true });
  for (const library of LIBRARIES) await mkdir(path.join(folder, library), { recursive: true });
  await Promise.all(
    CONDITION_ICONS.map((key) =>
      writeFile(path.join(folder, conditionIconFileOf(key)), whiteSvgOf(sets, key)),
    ),
  );
  const libraries = await readdir(folder);
  process.stdout.write(
    `ícones de condição: ${CONDITION_ICONS.length} SVG em ${libraries.length} pastas (${version})\n`,
  );
}

// `tsx scripts/generate-condition-icons.ts [--keys]`: `--keys` rewrites the contract list and the
// version (versioned files); without it, the SVG of the dev server and of the build.
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const sets = readIconSets();
  if (process.argv.includes('--keys')) await writeKeys(sets);
  else await writeSvgs(sets);
}
